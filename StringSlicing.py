name="python"
print(name[2:6])    # characters from index 2 to 5
print(name[2:])     # characters from index 2 to end
print(name[:6])     # characters from beginning to index 5
print(name[:])      # characters from beginning to end
print(name[::2])    # characters from beginning to end with a step of 2 
print(name[::-1]) # reverse the string